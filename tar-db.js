const _TARN={hp:'HP',atk:'ATK',def:'DEF'};
function tarLabel(c){
  const on=['hp','atk','def'].map(k=>[k,(c&&c[k])||0]).filter(x=>x[1]>0);
  if(!on.length)return '0';
  if(on.length===1)return _TARN[on[0][0]]+(on[0][1]>=2?'40%':'20%');
  const key=on.map(x=>_TARN[x[0]]).join('+')+'20%';
  return (TAR_M['체력형'][key]!==undefined)?key:'HP40%';
}
function tarPercent(bv,dtype,counts){
  const M=(TAR_M[dtype]||{})[tarLabel(counts)];
  if(!M||!bv)return null;
  const r=bv/M;
  return r<=1?Math.max(0,200*r-100):100*r;
}
function fmtTar(bv,dtype,counts){
  const t=tarPercent(bv,dtype,counts);
  return t===null?'':t.toFixed(1);
}
